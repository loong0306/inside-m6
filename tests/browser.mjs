import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

await mkdir('artifacts', {recursive:true});
const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1060},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5173');
  await page.waitForSelector('#scene canvas');
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  await page.locator('[data-module="memory"]').click();
  await page.getByRole('heading',{name:'统一内存 · 共用的数据空间'}).waitFor();
  await page.getByRole('button',{name:'暂停动画'}).click();
  await page.locator('#tab-1').click();
  assert.match(await page.locator('#scene').getAttribute('aria-label'),/cpu → cache/);
  await page.locator('#flow-mode').selectOption('hit');
  assert.equal(await page.locator('[data-step]').count(),2);
  await page.locator('#next-step').click();
  assert.match(await page.locator('#step-title').textContent(),/命中/);
  await page.locator('#flow-mode').selectOption('gpu');
  assert.equal(await page.locator('[data-step]').count(),4);
  await page.locator('[data-step="1"]').click();
  assert.match(await page.locator('#step-title').textContent(),/同步/);
  await page.screenshot({path:'artifacts/communication.png',fullPage:true});
  await page.locator('#tab-2').click();
  assert.equal(await page.locator('#period-value').textContent(),'0.208 ns');
  await page.locator('#frequency').fill('2.4');
  assert.equal(await page.locator('#cycles-value').textContent(),'24 亿次');
  assert.equal(await page.locator('#period-value').textContent(),'0.417 ns');
  await page.locator('#ipc').fill('0.5');
  assert.equal(await page.locator('#throughput-value').textContent(),'12.0 亿条 / 秒');
  const beforeStep = Number(await page.locator('#wave-cursor').getAttribute('x1'));
  await page.locator('#clock-step').click();
  const afterStep = Number(await page.locator('#wave-cursor').getAttribute('x1'));
  assert.ok(Math.abs(afterStep-beforeStep-145)<0.001);
  assert.match(await page.locator('#clock-cycle-count').textContent(),/1 个周期/);
  await page.getByRole('button',{name:'播放动画'}).waitFor();
  await page.screenshot({path:'artifacts/clock.png',fullPage:true});
  await page.locator('.source-button').click();
  await page.locator('#sources-dialog[open]').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('#tab-0').click();
  await page.locator('#reset-camera').click();
  await page.locator('#expand-view').click();
  await page.setViewportSize({width:850,height:900});
  await page.getByRole('button',{name:'数据如何旅行',exact:true}).waitFor();
  assert.equal(await page.locator('#expand-view').getAttribute('aria-pressed'),'true');
  await page.locator('#expand-view').click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#tab-2').click();
  await page.screenshot({path:'artifacts/mobile-clock.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  const reducedPage = await browser.newPage({reducedMotion:'reduce'});
  await reducedPage.goto('http://127.0.0.1:5173');
  await reducedPage.getByRole('button',{name:'播放动画'}).waitFor();
  await reducedPage.locator('#tab-1').click();
  assert.match(await reducedPage.locator('#scene').getAttribute('aria-label'),/cpu → cache/);
  await reducedPage.locator('#tab-0').click();
  await reducedPage.locator('#tab-1').click();
  assert.match(await reducedPage.locator('#scene').getAttribute('aria-label'),/cpu → cache/);
  const fallback = await browser.newPage();
  await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type.startsWith('webgl')?null:original.call(this,type,...args);};});
  await fallback.goto('http://127.0.0.1:5173');
  await fallback.getByText('3D 视图暂不可用',{exact:true}).waitFor();
  await fallback.locator('#tab-2').click();
  assert.equal(await fallback.locator('#period-value').textContent(),'0.208 ns');
  console.log('Browser checks passed: WebGL, module selection, flow scenarios, stepping, clock inputs, dialog, expansion, mobile overflow.');
} finally { await browser.close(); }
